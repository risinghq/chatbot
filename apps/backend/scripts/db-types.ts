import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";

// Writes src/db/schema.ts, the Kysely `Database` type and TENANT_TABLES, from
// the migrations. It applies them to an empty SQLite database and reads back
// each table, so the types follow what D1 holds after a deploy.
// tests/source/db-schema.test.ts fails when the committed file is stale.

const BACKEND = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MIGRATIONS = join(BACKEND, "migrations");
export const SCHEMA_FILE = join(BACKEND, "src/db/schema.ts");

type Column = {
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
};

type Table = { name: string; sql: string; columns: Column[] };

const HEADER = `// Generated by scripts/db-types.ts from migrations/. Do not edit:
// run \`bun run db:types\` after adding a migration.

import type { Generated } from "kysely";
`;

const TENANT_DOC =
  "/** Tables with a tenant_id column. db/tenant-scope.ts requires a predicate on each. */";

function readTables(dir: string): Table[] {
  const db = new DatabaseSync(":memory:");
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()) {
    db.exec(readFileSync(join(dir, file), "utf-8"));
  }
  const tables = db
    .prepare(
      `SELECT name, sql FROM sqlite_master
        WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
        ORDER BY name`,
    )
    .all() as { name: string; sql: string }[];
  const result = tables.map(({ name, sql }) => ({
    name,
    sql,
    columns: db.prepare(`PRAGMA table_info(${name})`).all() as Column[],
  }));
  db.close();
  return result;
}

/** `col IN ('a', 'b')` and `col IN (0, 1)` checks become literal unions. */
function checkedValues(tableSql: string): Map<string, string> {
  const unions = new Map<string, string>();
  for (const match of tableSql.matchAll(
    /CHECK\s*\(\s*(\w+)\s+IN\s*\(([^()]*)\)\s*\)/gi,
  )) {
    const values = match[2]!
      .split(",")
      .map((value) => value.trim())
      .filter((value) => /^('[^']*'|-?\d+)$/.test(value))
      .map((value) =>
        value.startsWith("'") ? `"${value.slice(1, -1)}"` : value,
      );
    if (values.length > 0) unions.set(match[1]!, values.join(" | "));
  }
  return unions;
}

function baseType(declared: string): string {
  const type = declared.toUpperCase();
  if (type.includes("INT") || type.includes("REAL") || type.includes("NUM")) {
    return "number";
  }
  if (type.includes("BLOB")) return "Uint8Array";
  return "string";
}

function pascalCase(name: string): string {
  return name.replace(/(^|_)(\w)/g, (_, __, c: string) => c.toUpperCase());
}

function columnType(column: Column, unions: Map<string, string>): string {
  let type = unions.get(column.name) ?? baseType(column.type);
  if (!column.notnull && !column.pk) type = `${type} | null`;
  const generated =
    column.dflt_value !== null ||
    (column.pk === 1 && column.type.toUpperCase() === "INTEGER");
  return generated ? `Generated<${type}>` : type;
}

function tableInterface(table: Table): string {
  const unions = checkedValues(table.sql);
  const columns = table.columns.map(
    (column) => `  ${column.name}: ${columnType(column, unions)};`,
  );
  return `export interface ${pascalCase(table.name)}Table {\n${columns.join("\n")}\n}`;
}

export function generateSchema(dir = MIGRATIONS): string {
  const tables = readTables(dir);
  const interfaces = tables.map(tableInterface).join("\n\n");
  const database = tables
    .map(({ name }) => `  ${name}: ${pascalCase(name)}Table;`)
    .join("\n");
  const tenantTables = tables
    .filter(({ columns }) => columns.some((c) => c.name === "tenant_id"))
    .map(({ name }) => `  "${name}",`)
    .join("\n");

  return [
    HEADER,
    interfaces,
    "",
    `export interface Database {\n${database}\n}`,
    "",
    TENANT_DOC,
    `export const TENANT_TABLES: ReadonlySet<string> = new Set([\n${tenantTables}\n]);\n`,
  ].join("\n");
}

if (import.meta.main) writeFileSync(SCHEMA_FILE, generateSchema());
